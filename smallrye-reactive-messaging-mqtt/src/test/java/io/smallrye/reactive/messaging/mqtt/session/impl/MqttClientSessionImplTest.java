    @Test
    void lifecycleDisconnectedToConnected() throws Exception {
        MqttClientSession session = MqttClientSession.create(vertx.getDelegate(), defaultOptions());
        List<SessionState> states = new CopyOnWriteArrayList<>();
        session.sessionStateHandler(e -> states.add(e.getSessionState()));

        assertThat(session.getState()).isEqualTo(SessionState.DISCONNECTED);

        session.start();

        await().atMost(10, TimeUnit.SECONDS)
                .until(() -> session.getState() == SessionState.CONNECTED);

        assertThat(states).contains(SessionState.CONNECTING, SessionState.CONNECTED);

        session.stop();
        await().atMost(10, TimeUnit.SECONDS)
                .until(() -> session.getState() == SessionState.DISCONNECTED);

        assertThat(states).contains(SessionState.DISCONNECTING, SessionState.DISCONNECTED);
    }

