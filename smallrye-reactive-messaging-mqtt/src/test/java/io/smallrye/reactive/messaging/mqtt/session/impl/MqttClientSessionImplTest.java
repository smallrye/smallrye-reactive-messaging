    @Test
    void pendingPublishesResentAfterReconnect() throws Exception {
        // Use a dedicated broker to avoid disrupting other tests
        try (GenericContainer<?> broker = new GenericContainer<>("eclipse-mosquitto:2.0")
                .withExposedPorts(1883)
                .withCopyFileToContainer(MountableFile.forClasspathResource("mosquitto.conf"),
                        "/mosquitto/config/mosquitto.conf")
                .waitingFor(Wait.forListeningPort())
                .waitingFor(Wait.forLogMessage(".*mosquitto .* running.*", 1))) {
            broker.start();
            MqttTestBase.awaitForMosquittoToBeReady(broker);

            MqttClientSessionOptions options = new MqttClientSessionOptions();
            options.setHostname(broker.getHost());
            options.setPort(broker.getMappedPort(1883));
            options.setCleanSession(false);
            options.setClientId("resend-test-" + System.currentTimeMillis());
            options.setPublishMaxRetries(5);
            options.setKeepAliveInterval(2);
            ConstantReconnectDelayOptions reconnect = new ConstantReconnectDelayOptions();
            reconnect.setDelay(Duration.ofSeconds(1));
            options.setReconnectDelay(reconnect);

            MqttClientSession session = MqttClientSession.create(vertx.getDelegate(), options);
            List<SessionState> states = new CopyOnWriteArrayList<>();
            session.sessionStateHandler(e -> states.add(e.getSessionState()));

            session.start();
            await().atMost(10, TimeUnit.SECONDS)
                    .until(() -> session.getState() == SessionState.CONNECTED);

            String topic = "test/resend/" + System.currentTimeMillis();

            // Pause the broker to prevent PUBACKs from arriving
            broker.getDockerClient().pauseContainerCmd(broker.getContainerId()).exec();
            try {
                var f = session.publish(topic, Buffer.buffer("will-retry"), MqttQoS.AT_LEAST_ONCE, false, false)
                        .toCompletionStage().toCompletableFuture();

                // Wait for the connection to drop
                await().atMost(30, TimeUnit.SECONDS)
                        .until(() -> states.contains(SessionState.DISCONNECTED));

                // Unpause the broker so reconnect can succeed
                broker.getDockerClient().unpauseContainerCmd(broker.getContainerId()).exec();

                // Session should reconnect and resend the pending publish
                await().atMost(30, TimeUnit.SECONDS)
                        .until(() -> session.getState() == SessionState.CONNECTED);

                Integer packetId = f.get(30, TimeUnit.SECONDS);
                assertThat(packetId).isNotNull();
            } finally {
                try {
                    broker.getDockerClient().unpauseContainerCmd(broker.getContainerId()).exec();
                } catch (Exception ignored) {
                }
            }

            session.stop();
            await().atMost(10, TimeUnit.SECONDS)
                    .until(() -> session.getState() == SessionState.DISCONNECTED);
        }
    }

